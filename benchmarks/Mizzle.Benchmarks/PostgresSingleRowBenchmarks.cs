using System.Data.Common;
using BenchmarkDotNet.Columns;
using BenchmarkDotNet.Configs;
using BenchmarkDotNet.Jobs;
using BenchmarkDotNet.Order;
using Testcontainers.PostgreSql;

namespace Mizzle.Benchmarks;

[MemoryDiagnoser]
[ShortRunJob]
[Orderer(SummaryOrderPolicy.FastestToSlowest)]
[GroupBenchmarksBy(BenchmarkLogicalGroupRule.ByCategory)]
[CategoriesColumn]
public class PostgresSingleRowBenchmarks
{
    private readonly BenchUsers _users = new();
    private PostgreSqlContainer? _container;
    private NpgsqlDataSource _dataSource = null!;
    private PostgresDb _db = null!;
    private int _id;

    [GlobalSetup]
    public async Task Setup()
    {
        var connectionString = Environment.GetEnvironmentVariable("MIZZLE_BENCH_POSTGRES");
        if (string.IsNullOrWhiteSpace(connectionString))
        {
            _container = new PostgreSqlBuilder().Build();
            await _container.StartAsync();
            connectionString = _container.GetConnectionString();
        }

        _dataSource = NpgsqlDataSource.Create(connectionString);
        _db = new PostgresDb(_dataSource);
        await Seed();
    }

    [GlobalCleanup]
    public async Task Cleanup()
    {
        if (_dataSource is not null)
        {
            await _dataSource.DisposeAsync();
        }

        if (_container is not null)
        {
            await _container.DisposeAsync();
        }
    }

    [Benchmark(Baseline = true)]
    [BenchmarkCategory("single-row")]
    public async Task<BenchUserRow> Raw_Npgsql()
    {
        await using var connection = await _dataSource.OpenConnectionAsync();
        await using var command = connection.CreateCommand();
        command.CommandText = "SELECT id, email FROM public.bench_users WHERE id = @id";
        command.Parameters.AddWithValue("id", _id);

        await using var reader = await command.ExecuteReaderAsync();
        if (!await reader.ReadAsync())
        {
            throw new InvalidOperationException("Seed row was not found.");
        }

        return ReadRow(reader);
    }

    [Benchmark(Baseline = true)]
    [BenchmarkCategory("thousand-rows")]
    public async Task<IReadOnlyList<BenchUserRow>> Raw_Npgsql_1000()
    {
        var rows = new List<BenchUserRow>(capacity: 1000);
        await using var connection = await _dataSource.OpenConnectionAsync();
        await using var command = connection.CreateCommand();
        command.CommandText = "SELECT id, email FROM public.bench_users ORDER BY id";

        await using var reader = await command.ExecuteReaderAsync();
        while (await reader.ReadAsync())
        {
            rows.Add(ReadRow(reader));
        }

        return rows;
    }

    [Benchmark]
    [BenchmarkCategory("single-row")]
    public async Task<BenchUserRow> Dapper_QuerySingle()
    {
        await using var connection = await _dataSource.OpenConnectionAsync();
        return await connection.QuerySingleAsync<BenchUserRow>(
            "SELECT id, email FROM public.bench_users WHERE id = @id",
            new { id = _id });
    }

    [Benchmark]
    [BenchmarkCategory("thousand-rows")]
    public async Task<IReadOnlyList<BenchUserRow>> Dapper_Query_1000()
    {
        await using var connection = await _dataSource.OpenConnectionAsync();
        var rows = await connection.QueryAsync<BenchUserRow>(
            "SELECT id, email FROM public.bench_users ORDER BY id");
        return rows.AsList();
    }

    [Benchmark]
    [BenchmarkCategory("single-row")]
    public async Task<BenchUserRow> Mizzle_Runtime_Mapper()
        => await _db.Select(_users.Id, _users.Email)
            .From(_users)
            .Where(_users.Id.Eq(_id))
            .SingleAsync(ReadRow);

    [Benchmark]
    [BenchmarkCategory("thousand-rows")]
    public async Task<IReadOnlyList<BenchUserRow>> Mizzle_Runtime_Mapper_1000()
        => await _db.Select(_users.Id, _users.Email)
            .From(_users)
            .OrderBy(_users.Id)
            .ToListAsync(ReadRow);

    [Benchmark]
    [BenchmarkCategory("single-row")]
    public async Task<BenchUserRow> Mizzle_Generated_Projection()
        => await _db.Select(_users.Id, _users.Email)
            .From(_users)
            .Where(_users.Id.Eq(_id))
            .SingleAsync<BenchUserRow>();

    [Benchmark]
    [BenchmarkCategory("thousand-rows")]
    public async Task<IReadOnlyList<BenchUserRow>> Mizzle_Generated_Projection_1000()
        => await _db.Select(_users.Id, _users.Email)
            .From(_users)
            .OrderBy(_users.Id)
            .ToListAsync<BenchUserRow>();

    private async Task Seed()
    {
        await using var connection = await _dataSource.OpenConnectionAsync();
        await connection.ExecuteAsync("""
            CREATE TABLE IF NOT EXISTS public.bench_users (
                id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                email text NOT NULL
            );

            TRUNCATE TABLE public.bench_users RESTART IDENTITY;

            INSERT INTO public.bench_users (email)
            SELECT 'user-' || g || '@example.com'
            FROM generate_series(1, 1000) AS g;
            """);

        _id = await connection.ExecuteScalarAsync<int>(
            "SELECT id FROM public.bench_users WHERE email = 'user-500@example.com'");
    }

    private static BenchUserRow ReadRow(DbDataReader reader)
        => new(reader.GetInt32(0), reader.GetString(1));
}

public sealed record BenchUserRow(int Id, string Email);

internal sealed class BenchUsers : PgTable<BenchUsers>
{
    public BenchUsers() : base("bench_users", "public", "bu") { }

    public PgColumn<int> Id { get; } = Identity("id").PrimaryKey();
    public PgColumn<string> Email { get; } = Text("email").NotNull();
}
